// Installs the six Pigeon host APIs and the event stream handler of ARCH §12.6 on one Flutter
// engine's messenger, and removes them when that engine detaches. Every Flutter engine shares the
// process EngineContext (services, threads, EventHub); each gets its own preview port (its texture
// registry) and event sink.

package com.vecvel.danaview.editor.engine.glue

import com.vecvel.danaview.editor.engine.core.EngineContext
import com.vecvel.danaview.editor.engine.core.LaneSpec
import com.vecvel.danaview.editor.engine.pigeon.EngineHostApi
import com.vecvel.danaview.editor.engine.pigeon.EngineEventsStreamHandler
import com.vecvel.danaview.editor.engine.pigeon.ExportHostApi
import com.vecvel.danaview.editor.engine.pigeon.JobsHostApi
import com.vecvel.danaview.editor.engine.pigeon.PlatformHostApi
import com.vecvel.danaview.editor.engine.pigeon.PreviewHostApi
import com.vecvel.danaview.editor.engine.pigeon.RecorderHostApi
import io.flutter.plugin.common.BinaryMessenger
import io.flutter.plugin.common.EventChannel
import io.flutter.view.TextureRegistry

/** The glue installed on one Flutter engine. Create with [attach]; call [detach] once. */
class GlueRegistrar private constructor(
    private val ctx: EngineContext,
    private val messenger: BinaryMessenger,
    private val previewPort: PreviewPort,
    private val platformPort: ContextPlatformPort,
    private val events: EngineEventsHandler,
) {
    /** Removes every handler from the messenger and releases this engine's preview sessions. */
    fun detach() {
        EngineHostApi.setUp(messenger, null)
        PreviewHostApi.setUp(messenger, null)
        JobsHostApi.setUp(messenger, null)
        ExportHostApi.setUp(messenger, null)
        RecorderHostApi.setUp(messenger, null)
        PlatformHostApi.setUp(messenger, null)
        EventChannel(messenger, EVENTS_CHANNEL).setStreamHandler(null)
        events.detach()
        try {
            platformPort.cancelMaterializations()
        } catch (t: Throwable) {
            GlueLog.warn("pick copy cancel", t)
        }
        // Nothing to release (and no lane to start) when this process never opened a preview.
        if (ctx.threads.started().none { it.spec == LaneSpec.PREVIEW }) return
        try {
            ctx.threads.preview.execute {
                try {
                    previewPort.releaseAll()
                } catch (t: Throwable) {
                    GlueLog.warn("preview release", t)
                }
            }
        } catch (t: Throwable) {
            GlueLog.warn("preview release", t)
        }
    }

    companion object {
        /** Channel name of `EngineEventsApi.engineEvents` (generated by Pigeon, no instance suffix). */
        const val EVENTS_CHANNEL = "dev.flutter.pigeon.danaview_editor_engine.EngineEventsApi.engineEvents"

        /** Installs the host APIs and the event stream on [messenger]. */
        fun attach(ctx: EngineContext, messenger: BinaryMessenger, textures: TextureRegistry): GlueRegistrar {
            val threads = ctx.threads
            val dispatch = GlueDispatcher(threads.main)
            val paths = { ctx.pathsOrNull }
            val root = ContextEngineRootPort(ctx)
            val previewPort = ContextPreviewPort(ctx, textures)

            EngineHostApi.setUp(messenger, EngineHostApiImpl(threads, root, dispatch))
            PreviewHostApi.setUp(messenger, PreviewHostApiImpl(threads, previewPort, dispatch, paths))
            JobsHostApi.setUp(messenger, JobsHostApiImpl(threads, ContextJobsPort(ctx), paths, dispatch))
            ExportHostApi.setUp(messenger, ExportHostApiImpl(threads, ContextExportPort(ctx), paths, dispatch))
            RecorderHostApi.setUp(messenger, RecorderHostApiImpl(threads, ContextRecorderPort(ctx), paths, dispatch))
            val platformPort = ContextPlatformPort(ctx)
            PlatformHostApi.setUp(messenger, PlatformHostApiImpl(threads, platformPort, paths, dispatch))

            val events = EngineEventsHandler(ctx.events)
            EngineEventsStreamHandler.register(messenger, events)

            MemorySignals.installOnce(ctx.appContext, ctx.events, { ctx.pathsOrNull != null }) { level -> root.trimCaches(level) }
            RecordingSignals.installOnce(ctx)
            return GlueRegistrar(ctx, messenger, previewPort, platformPort, events)
        }
    }
}
